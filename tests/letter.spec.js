import { test, expect } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
import { PDFDocument } from 'pdf-lib';

test('publishes the parody generator schema in HTML without requiring JavaScript', async ({ request }) => {
  const response = await request.get('/');
  expect(response.ok()).toBe(true);
  const head = (await response.text()).split('</head>')[0];
  const declarations = [...head.matchAll(/<script\b[^>]*type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)];
  expect(declarations).toHaveLength(1);
  const data = JSON.parse(declarations[0][1]);
  expect(data['@context']).toBe('https://schema.org');
  expect(data['@type']).toBe('WebApplication');
  expect(data.url).toBe('https://carta.guigoes.com/');
  expect(data.applicationCategory).toBe('EntertainmentApplication');
  expect(data.genre).toBe('Paródia política');
  expect(data.description).toMatch(/cartas fictícias.*paródia política, sem valor oficial/);
  expect(data.isAccessibleForFree).toBe(true);
});

test('personalizes the letter and exports one matching PNG and A4 PDF', async ({ page }) => {
  await mkdir('output/pdf', { recursive: true });
  const errors = [];
  const externalRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:4317/')) externalRequests.push(request.url()); });
  await page.setViewportSize({ width: 1365, height: 1100 });
  await page.goto('/');
  await expect(page.getByRole('link', { name: 'Carta, início' })).toHaveText('carta');
  await expect(page.getByRole('link', { name: 'Código-fonte' })).toHaveAttribute('href', 'https://github.com/guilycst/carta-autoproclamada');
  await expect(page.getByAltText('Brasão paródico da República Autoproclamada do Brazil')).toBeVisible();
  expect(await page.locator('#national-emblem').evaluate(image => image.naturalWidth)).toBe(1254);
  await page.getByLabel('Qual é seu nome?').fill('Joana da Conceição');
  await page.getByLabel('Como devemos chamar você?').selectOption('presidenta');
  await page.getByLabel('De onde vai governar?').fill('República da minha varanda');
  await expect(page.locator('#letter-transcript')).toContainText('Joana da Conceição');
  await expect(page.locator('#letter-transcript')).toContainText('República da minha varanda');
  await expect(page.locator('#letter-transcript')).toContainText('presidenta por vontade própria');
  const pixels = await page.locator('canvas').evaluate(canvas => canvas.toDataURL());
  const pngDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Baixar PNG' }).click();
  await (await pngDownload).saveAs('output/carta.png');
  const png = await readFile('output/carta.png');
  expect(png.readUInt32BE(16)).toBe(2160);
  expect(png.readUInt32BE(20)).toBe(3056);
  expect(`data:image/png;base64,${png.toString('base64')}`).toBe(pixels);
  const pdfDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Baixar PDF' }).click();
  await (await pdfDownload).saveAs('output/pdf/carta.pdf');
  const pdf = await PDFDocument.load(await readFile('output/pdf/carta.pdf'));
  expect(pdf.getPageCount()).toBe(1);
  expect(pdf.getPage(0).getWidth()).toBeCloseTo(595.28, 2);
  expect(pdf.getPage(0).getHeight()).toBeCloseTo(841.89, 2);
  expect(pdf.getTitle()).toContain('Joana da Conceição');
  await page.screenshot({ path: 'output/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.getByLabel('Qual é seu nome?').fill('Joana da Conceição');
  await page.getByLabel('Como devemos chamar você?').selectOption('presidenta');
  await page.locator('h1').click();
  const previewBox = await page.locator('.preview').boundingBox();
  const actionsBox = await page.locator('.actions').boundingBox();
  expect(actionsBox.y).toBeGreaterThanOrEqual(previewBox.y + previewBox.height);
  await page.screenshot({ path: 'output/mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await page.locator('canvas').boundingBox()).width).toBeGreaterThan(300);
  const mobileDownload = page.waitForEvent('download');
  await page.getByLabel('Qual é seu nome?').press('Enter');
  expect((await mobileDownload).suggestedFilename()).toBe('minha-autoproclamacao.png');
  expect(errors).toEqual([]);
  expect(externalRequests).toEqual([]);
});

test('blocks exports when the national coat of arms cannot load', async ({ page }) => {
  await page.route('**/brasao-parodia.png', route => route.abort());
  await page.goto('/');
  await expect(page.getByRole('status')).toContainText('Não foi possível carregar o brasão.');
  await expect(page.getByRole('button', { name: 'Baixar PNG' })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Baixar PDF' })).toBeDisabled();
});

test('handles long unbroken names and treats markup as text', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Qual é seu nome?').fill('Á'.repeat(80));
  await page.getByLabel('De onde vai governar?').fill('É'.repeat(60));
  await expect(page.locator('#letter-transcript')).toContainText('Á'.repeat(80));
  await expect(page.getByRole('status')).toHaveText('');
  await page.locator('canvas').screenshot({ path: 'output/long-name.png' });
  await page.getByLabel('Qual é seu nome?').fill('<img src=x onerror=alert(1)>');
  await expect(page.locator('#letter-transcript')).toContainText('<img src=x onerror=alert(1)>');
  await expect(page.locator('#letter-transcript img')).toHaveCount(0);
  await page.getByLabel('Qual é seu nome?').fill('   ');
  await page.getByRole('button', { name: 'Baixar PDF' }).click();
  await expect(page.getByRole('status')).toHaveText('Preencha seu nome para gerar a carta.');
});
